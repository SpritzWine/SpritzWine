//! Steam Play compatibility-tool descriptors generated for the Steam target.
//!
//! A bare Wine build is not itself a Steam Play tool: Steam only invokes tools that speak
//! Proton's protocol. The three files below are the minimum that makes the relocatable
//! SpritzWine tree appear under *"Force a specific Steam Play compatibility tool"* and
//! actually launch a title:
//!
//! * [`compatibilitytool_vdf`] -- registers the tool (Steam reads this to list it),
//! * [`toolmanifest_vdf`] -- points Steam at the [`ENTRY_POINT`] script,
//! * [`PROTON_WRAPPER`] -- a small shim that maps Steam's verbs and `STEAM_COMPAT_DATA_PATH`
//!   onto the bundled `bin/wine`.
//!
//! These are written *only* into a chosen Steam tool directory by the installer; the
//! generic build/tarball never contains them. The wrapper runs host-native (no Steam Linux
//! Runtime container), matching the host-linked relocatable tree.
//!
//! The entry point is deliberately **not** named `proton`: Lutris (and similar) auto-import
//! every Steam compatibility tool whose directory contains a file literally named `proton`,
//! treat it as a Proton build, and then look for its wine at the Proton layout
//! `files/bin/wine` -- which ours isn't -- crashing with "missing its wine executable". By
//! calling it [`ENTRY_POINT`] (and pointing the manifest's `commandline` at it, as
//! non-Proton tools like Boxtron/Luxtorpeda do) Steam still launches it, while Lutris leaves
//! it alone and a separate plain-Wine Lutris runner works without collision.

/// The Steam entry-point script's filename (see the module note on why it isn't `proton`).
pub const ENTRY_POINT: &str = "spritzwine-proton";

/// `compatibilitytool.vdf` -- the registration Steam reads at startup. `install_path "."`
/// means "this directory is the tool"; the internal key and `display_name` are `name`.
pub fn compatibilitytool_vdf(name: &str) -> String {
    format!(
        r#""compatibilitytools"
{{
  "compat_tools"
  {{
    "{name}"
    {{
      "install_path" "."
      "display_name" "{name}"
      "from_oslist" "windows"
      "to_oslist" "linux"
    }}
  }}
}}
"#
    )
}

/// `toolmanifest.vdf` -- tells Steam how to invoke the tool. `%verb%` is substituted by
/// Steam (e.g. `waitforexitandrun`). No `require_tool_appid`, so it runs directly on the
/// host rather than inside the Steam Linux Runtime container.
pub fn toolmanifest_vdf() -> String {
    r#""manifest"
{
  "version" "2"
  "commandline" "/spritzwine-proton %verb%"
}
"#
    .to_string()
}

/// The `proton` entry point (mode `0755`). Steam runs it as `proton <verb> [command...]`.
pub const PROTON_WRAPPER: &str = r#"#!/usr/bin/env bash
# SpritzWine Steam Play wrapper -- generated by the SpritzWine installer.
#
# Steam invokes:   proton <verb> [command...]
# This speaks the minimum of Proton's protocol needed to launch a title with the bundled,
# relocatable SpritzWine build. It runs host-native (no Steam Linux Runtime container),
# matching the host-linked tree.
set -u

HERE="$(cd "$(dirname "$(readlink -f "$0")")" && pwd)"

export WINELOADER="$HERE/bin/wine"
export WINESERVER="$HERE/bin/wineserver"
# The bundled Rust unix libs sit next to the unixlibs that DT_NEEDED them; LD_LIBRARY_PATH
# is searched before the build-tree RUNPATH, which is what makes the tree relocatable.
export LD_LIBRARY_PATH="$HERE/lib/wine/x86_64-unix:$HERE/lib:${LD_LIBRARY_PATH:-}"

# Steam hands us a per-game compat-data dir; the Windows prefix lives in pfx/.
if [ -n "${STEAM_COMPAT_DATA_PATH:-}" ]; then
    export WINEPREFIX="$STEAM_COMPAT_DATA_PATH/pfx"
else
    export WINEPREFIX="${WINEPREFIX:-$HOME/.spritzwine}"
fi
mkdir -p "$WINEPREFIX"

# First-run prefix init (cheap no-op once system.reg exists).
if [ ! -f "$WINEPREFIX/system.reg" ]; then
    "$HERE/bin/wine" wineboot -i >/dev/null 2>&1 || true
fi

verb="${1:-run}"
[ "$#" -gt 0 ] && shift

case "$verb" in
    run|waitforexitandrun|runinprefix)
        exec "$HERE/bin/wine" "$@"
        ;;
    getcompatpath|getnativepath)
        # Minimal path passthrough -- Steam uses these for path translation.
        printf '%s' "${1:-}"
        ;;
    *)
        exec "$HERE/bin/wine" "$@"
        ;;
esac
"#;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn compat_vdf_embeds_name() {
        let v = compatibilitytool_vdf("SpritzWine");
        assert!(v.contains("\"SpritzWine\""));
        assert!(v.contains("\"install_path\" \".\""));
        assert!(v.contains("\"to_oslist\" \"linux\""));
    }

    #[test]
    fn manifest_points_at_entry_point() {
        let m = toolmanifest_vdf();
        assert!(m.contains(&format!("\"commandline\" \"/{ENTRY_POINT} %verb%\"")));
        // Not literally `/proton ...`, which is what makes Lutris misclassify it.
        assert!(!m.contains("\"/proton %verb%\""));
    }

    #[test]
    fn wrapper_is_bash_and_handles_verbs() {
        assert!(PROTON_WRAPPER.starts_with("#!/usr/bin/env bash"));
        assert!(PROTON_WRAPPER.contains("STEAM_COMPAT_DATA_PATH"));
        assert!(PROTON_WRAPPER.contains("waitforexitandrun"));
    }
}
