#!/usr/bin/env bash
# Post-commit fixups for a consumer replay: the corrections rerere cannot hold
# because the replayed commit merges cleanly and is still wrong on the new base.
#
# Run from the wine tree after each replayed commit, i.e. as the rebase's
# `exec` step. Amends HEAD when it changes anything. Every fixup is keyed on
# the base's own content, so it is a no-op on a base that does not need it.
set -euo pipefail

touched() { git diff --name-only HEAD^ HEAD | grep -qx -e "$1"; }
dirty=()

# wine 11.16 moved unix_mount from struct disk_device to struct volume.
f=dlls/mountmgr.sys/device.c
if touched "$f" && grep -q 'volume->unix_mount' "$f" &&
   grep -q 'disk_device->unix_mount' "$f"; then
    sed -i 's/disk_device->unix_mount/volume->unix_mount/g' "$f"
    dirty+=("$f")
fi

# A textual merge of the generated configure mixes generator versions.
# Regenerate, but only with the autoconf the base itself was generated by;
# any other version rewrites thousands of unrelated lines.
if git ls-files --error-unmatch configure >/dev/null 2>&1 &&
   { touched configure || touched configure.ac || touched include/config.h.in; }; then
    want=$(sed -n 's/^# Generated by GNU Autoconf \([0-9.]*\).*/\1/p' configure | head -1)
    have=$(autoconf --version | sed -n '1s/.* //p')
    if [ "$want" = "$have" ]; then
        autoreconf -f
        rm -rf autom4te.cache 'configure~'
        git diff --quiet -- configure || dirty+=(configure)
        git diff --quiet -- include/config.h.in || dirty+=(include/config.h.in)
    else
        echo ">> replay-fixups: configure wants autoconf $want, host has $have; not regenerated" >&2
    fi
fi

if [ "${#dirty[@]}" -gt 0 ]; then
    git add -- "${dirty[@]}"
    git commit -q --amend --no-edit
    echo ">> replay-fixups: amended $(git rev-parse --short HEAD): ${dirty[*]}"
fi
