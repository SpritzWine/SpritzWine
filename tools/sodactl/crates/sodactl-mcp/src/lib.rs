/// `check`, with the counts the CLI's summary line shows.
///
/// The findings are core `Finding` values passed through untouched. The counts
/// are the only addition, and they are here because a caller that wants "is the
/// graph shippable" should not have to fold a list to find out.
#[derive(Debug, Serialize)]
pub struct CheckResult {
    pub severity_min: String,
    pub blocker: usize,
    pub drift: usize,
    pub hygiene: usize,
    pub findings: Vec<Finding>,
}

/// `explain`, which answers with or without a repository.
///
/// A miss returns the catalogue rather than an error: a model that guessed a
/// code wrong recovers in the same turn instead of spending a round trip on a
/// second tool call.
#[derive(Debug, Serialize)]
pub struct ExplainResult {
    pub queried: String,
    pub doc: Option<&'static explain::CodeDoc>,
    /// Populated only on a miss.
    pub known_codes: Vec<&'static str>,
}

