#[derive(Debug, Deserialize, schemars::JsonSchema)]
pub struct CheckArgs {
    /// Lowest severity to report: `blocker`, `drift` or `hygiene`.
    /// Omitted means everything -- a lint that hides its own hygiene findings by
    /// default trains you to believe the graph is clean.
    pub severity_min: Option<String>,
}

#[derive(Debug, Deserialize, schemars::JsonSchema)]
pub struct ExplainArgs {
    /// A finding code, e.g. `TIER_CHILD_STALE`. Case-insensitive.
    pub code: String,
}

