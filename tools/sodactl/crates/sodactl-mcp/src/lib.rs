/// The three rules a model cannot infer from the tool list and that are
/// expensive to violate. Carried on `initialize`, so they are in context before
/// the first call rather than discovered from a refusal.
const INSTRUCTIONS: &str = "\
SpritzWine release-graph state. All tools are read-only.

Three project rules that the tool surface cannot enforce and that a plausible-looking action \
will violate:

1. Never author commits on a `spritzwine`/`spritzvalve` branch. Consumers are GENERATED by \
replaying tiers and are force-pushed; a hand commit there is destroyed without warning on the \
next regeneration. Author on the owning `soda-*` tier instead.

2. Never rebase a `soda-*` tier onto a wine base. Tiers are authored on `repo.home_base`. \
Moving one onto a wine base invalidates every rerere-cache entry at once, which converts every \
future replay into a manual merge session.

3. The user performs all pushes. There is no push tool and there will not be one \
(no ssh-agent, Codeberg only, submodule before superproject). Print the commands; do not run them.

Reasoning about replayed history: stitches are built by cherry-pick and consumers by rebase, so \
the original tier commits are NEVER ancestors of the result. Ancestry, SHA equality and commit \
counts all give confident wrong answers there -- patch-id equivalence is the only correct \
primitive, and `sodactl_status` already applies it. Do not re-derive freshness by eye from \
`git log`.";

