//! The MCP surface: `sodactl` as tools a model can call.
//!
//! Read-only, deliberately and entirely. Every tool here answers a question; not
//! one of them moves a ref. That is not a phasing accident -- it is what makes
//! the whole surface safe to leave enabled with no permission friction, which is
//! the only way it gets used often enough to be worth having. The mutating half
//! (`sodactl_apply`, one entry point, elicitation, backup refs, CAS) arrives with
//! v2's plan/apply split and lands beside this, not inside it.
//!
//! # One schema, N surfaces
//!
//! Nothing here computes anything. `status` calls the same
//! `sodactl_core::reconcile` the CLI calls and hands back the same `Report`;
//! `tier_graph` and `rr_health` call the same module functions. A tool that
//! reformatted, summarised or re-derived would be a second implementation of the
//! domain model reachable only from a surface nobody diffs against the first.
//! The moment MCP and `--json` can disagree, one of them is wrong and there is no
//! test that says which.
//!
//! # STDOUT IS THE PROTOCOL
//!
//! Under `transport-io`, stdout *is* the JSON-RPC channel. A single stray
//! `println!` anywhere in this process -- including deep in a dependency, or in a
//! debugging `dbg!` that survived a commit -- injects a non-frame into the stream
//! and corrupts it. The failure does not surface here: the client desynchronises
//! and reports something unrelated-looking several tool calls later, which is
//! about the worst debugging experience this codebase could produce.
//!
//! Three things hold the line, in increasing order of how much they are worth:
//!
//!   1. Convention: log to stderr. Necessary, insufficient, forgettable.
//!   2. `no_stdout_writes` below: a test that greps this crate and
//!      `sodactl-core` for stdout writes and fails the build. Crude, and crude is
//!      the point -- it costs nothing and it fires on the commit, not in a
//!      client three weeks later.
//!   3. Never linking the renderer. `sodactl-cli` owns every `println!` in the
//!      workspace and this crate does not depend on it. The dependency graph is
//!      the real enforcement; the test only catches a regression that would
//!      change the graph's meaning.
//!
//! # Why the outputs are schema-opaque
//!
//! `Json<T>` wants `T: Serialize + JsonSchema`, and the core types derive only
//! `Serialize` today. Rather than fork them into MCP-shaped copies -- which would
//! be the drift this crate exists to prevent -- `Opaque<T>` supplies a permissive
//! output schema and serialises `T` verbatim. Clients get exact structured
//! content; they get a loose declaration of its shape. The proper fix is one
//! `#[derive(JsonSchema)]` per core type behind a `schemars` feature on
//! `sodactl-core`, and this wrapper deletes itself the day that lands. Inputs are
//! not opaque: argument schemas are how a model knows what to pass, so those are
//! real derived schemas on local types.

pub mod ctx;
pub mod rr;

