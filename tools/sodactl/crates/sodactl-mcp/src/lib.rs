#[derive(Clone)]
pub struct Sodactl {
    ctx: Arc<Ctx>,
}

impl Sodactl {
    pub fn new(ctx: Ctx) -> Self {
        Self { ctx: Arc::new(ctx) }
    }
}

/// Git reads block, and some of them block for a noticeable time -- not
/// `status`, which is ~33 ms on this tree's 12,434 tracked files (the "6.5 GB"
/// this comment used to cite is PACK data, which `status` never walks), but the
/// history walks: `missing_by_patch_id` runs a `git cherry` per tier and
/// `reapply_verdict` a `merge-tree` per rerere postimage, and a full reconcile
/// is measured in seconds.
///
/// Running them on the reactor would stall the JSON-RPC loop -- including
/// the client's ability to cancel the very call that is stalling it -- so every
/// tool body goes to a blocking thread. The `Arc<Ctx>` clone is what makes that
/// possible; it is not premature sharing.
async fn blocking<T, F>(f: F) -> Result<T, ErrorData>
where
    F: FnOnce() -> anyhow::Result<T> + Send + 'static,
    T: Send + 'static,
{
    match tokio::task::spawn_blocking(f).await {
        Ok(Ok(v)) => Ok(v),
        // `{:#}` prints the anyhow context chain. The chain is the message here:
        // "reading manifest X" alone is useless without the io error under it.
        Ok(Err(e)) => Err(ErrorData::internal_error(format!("{e:#}"), None)),
        Err(e) => Err(ErrorData::internal_error(format!("tool task panicked: {e}"), None)),
    }
}

#[tool_router]
impl Sodactl {
    /// The whole graph as it stands: tiers with derived commit counts and
    /// ahead/behind, stitch and consumer freshness by patch-id, plus every
    /// finding. Start here -- it is one call in place of the six git commands a
    /// session otherwise spends reconstructing the same picture.
    #[tool(name = "sodactl_status")]
    pub async fn status(&self) -> Result<Json<Opaque<sodactl_core::Report>>, ErrorData> {
        let ctx = self.ctx.clone();
        blocking(move || sodactl_core::reconcile(&ctx.manifest, &ctx.git))
            .await
            .map(|r| Json(Opaque(r)))
    }

    /// Only what is wrong, optionally gated by severity. Codes are stable, so
    /// they can be reasoned about and allowlisted in CI. Pair with
    /// `sodactl_explain` before proposing a fix -- several of these have a
    /// plausible wrong fix that corrupts history.
    #[tool(name = "sodactl_check")]
    pub async fn check(
        &self,
        Parameters(args): Parameters<CheckArgs>,
    ) -> Result<Json<Opaque<CheckResult>>, ErrorData> {
        let min = match args.severity_min.as_deref() {
            None | Some("hygiene") => Severity::Hygiene,
            Some("drift") => Severity::Drift,
            Some("blocker") => Severity::Blocker,
            Some(other) => {
                return Err(ErrorData::invalid_params(
                    format!("unknown severity `{other}` (blocker|drift|hygiene)"),
                    None,
                ))
            }
        };

        let ctx = self.ctx.clone();
        let report = blocking(move || sodactl_core::reconcile(&ctx.manifest, &ctx.git)).await?;

        // `Severity` orders Blocker < Drift < Hygiene, so "at or above the gate"
        // is `<= min`. Counts are of the FILTERED set, so they always describe
        // the list actually returned rather than a hidden superset.
        let findings: Vec<Finding> =
            report.findings.iter().filter(|f| f.severity <= min).cloned().collect();
        let count = |s: Severity| findings.iter().filter(|f| f.severity == s).count();

        Ok(Json(Opaque(CheckResult {
            severity_min: args.severity_min.unwrap_or_else(|| "hygiene".into()),
            blocker: count(Severity::Blocker),
            drift: count(Severity::Drift),
            hygiene: count(Severity::Hygiene),
            findings,
        })))
    }

    /// What a finding code means, the failure it predicts if ignored, and how to
    /// clear it -- including what NOT to do. `docs/BRANCHING.md` as a queryable
    /// structure. Touches no repository, so it is answerable from anywhere.
    #[tool(name = "sodactl_explain")]
    pub async fn explain(
        &self,
        Parameters(args): Parameters<ExplainArgs>,
    ) -> Result<Json<Opaque<ExplainResult>>, ErrorData> {
        let doc = explain::lookup(&args.code);
        Ok(Json(Opaque(ExplainResult {
            queried: args.code,
            doc,
            known_codes: if doc.is_some() {
                vec![]
            } else {
                explain::CATALOGUE.iter().map(|d| d.code).collect()
            },
        })))
    }

    /// The tier DAG with staleness propagated down it, and the order a restack
    /// must run in. The order is the value: restacking a child before its parent
    /// rebases it onto a tip that is about to move, so the work is thrown away
    /// and the second pass starts from a commit set the first pass no longer
    /// describes.
    #[tool(name = "sodactl_tier_graph")]
    pub async fn tier_graph(&self) -> Result<Json<Opaque<graph::Dag>>, ErrorData> {
        let ctx = self.ctx.clone();
        blocking(move || graph::tier_graph(&ctx.manifest, &ctx.git)).await.map(|d| Json(Opaque(d)))
    }

    /// Health of the tracked `tools/rr-cache`: entries recorded but never
    /// resolved (which stop every future replay while the cache's existence
    /// implies the opposite), and stray transient state that was committed from
    /// a tree captured mid-conflict.
    #[tool(name = "sodactl_rr_health")]
    pub async fn rr_health(&self) -> Result<Json<Opaque<rr::RrHealth>>, ErrorData> {
        let ctx = self.ctx.clone();
        blocking(move || rr::rr_health(&ctx.rr_cache_dir())).await.map(|h| Json(Opaque(h)))
    }
}

/// `#[tool_handler]` fills in `call_tool`/`list_tools` and would also synthesise
/// `get_info` -- but its `instructions = "..."` attribute takes a string
/// *literal*, and inlining the block above into an attribute makes it
/// unreadable and un-greppable. The macro skips any method already present, so
/// writing `get_info` by hand keeps the instructions as a named const.
#[tool_handler]
impl ServerHandler for Sodactl {
    fn get_info(&self) -> rmcp::model::ServerInfo {
        // `ServerInfo` is `#[non_exhaustive]`, so it cannot be built with a
        // struct expression even with `..Default::default()` -- rmcp reserves
        // the right to add fields as the MCP spec revises. Mutating a default is
        // the intended shape and is also the one that keeps compiling across a
        // 2.x bump that adds a field.
        let mut info = rmcp::model::ServerInfo::default();
        info.capabilities = rmcp::model::ServerCapabilities::builder().enable_tools().build();
        info.instructions = Some(INSTRUCTIONS.to_string());
        info
    }
}

/// Serve on stdio until the client disconnects.
///
/// Takes the manifest path rather than a `Ctx` so the caller cannot accidentally
/// build one against a different repository than `sodactl status` would; the
/// derivation lives in `Ctx::load` and there is exactly one of it.
pub async fn serve_stdio(manifest_path: impl AsRef<std::path::Path>) -> anyhow::Result<()> {
    use rmcp::transport::stdio;
    use rmcp::ServiceExt;

    let ctx = Ctx::load(manifest_path)?;
    let service = Sodactl::new(ctx).serve(stdio()).await?;
    service.waiting().await?;
    Ok(())
}

// ---------------------------------------------------------------------------
// Opaque: the schema shim. See the module header for why it exists and when it
// should be deleted.
// ---------------------------------------------------------------------------

/// Serialises `T` verbatim; declares a permissive JSON Schema for it.
///
/// The structured content a client receives is byte-identical to what
/// `sodactl --json` prints, because it is the same `Serialize` impl. Only the
/// *declaration* is loose.
pub struct Opaque<T>(pub T);

impl<T: Serialize> Serialize for Opaque<T> {
    fn serialize<S: serde::Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
        self.0.serialize(s)
    }
}

/// A stable schema name and top-level JSON shape for a type that does not derive
/// `JsonSchema`. A local trait, so implementing it for foreign types is fine.
///
/// The name must be stable: clients key cached schemas on it, and a name derived
/// from `std::any::type_name` would silently change with a module move.
pub trait OpaqueSchema {
    const SCHEMA_NAME: &'static str;
    /// `"object"` or `"array"`. Enough for a client to know whether to index it.
    const SHAPE: &'static str = "object";
}

impl OpaqueSchema for sodactl_core::Report {
    const SCHEMA_NAME: &'static str = "SodactlStatusReport";
}
impl OpaqueSchema for CheckResult {
    const SCHEMA_NAME: &'static str = "SodactlCheckResult";
}
impl OpaqueSchema for ExplainResult {
    const SCHEMA_NAME: &'static str = "SodactlExplainResult";
}
impl OpaqueSchema for graph::Dag {
    const SCHEMA_NAME: &'static str = "SodactlTierGraph";
}
impl OpaqueSchema for rr::RrHealth {
    const SCHEMA_NAME: &'static str = "SodactlRrHealth";
}

impl<T: OpaqueSchema> schemars::JsonSchema for Opaque<T> {
    fn schema_name() -> std::borrow::Cow<'static, str> {
        T::SCHEMA_NAME.into()
    }

    fn json_schema(_: &mut schemars::SchemaGenerator) -> schemars::Schema {
        // `additionalProperties` stays open on purpose: this schema is a hint,
        // and a closed one would assert a field list we are not deriving and
        // would therefore get wrong the first time a core type gains a field.
        schemars::json_schema!({
            "type": T::SHAPE,
            "description": "Structured sodactl output. Identical to `sodactl --json`; \
the field list is not declared here (see sodactl-mcp's Opaque)."
        })
    }
}

// ---------------------------------------------------------------------------
// Tests. Both are source-greps, which is unusual and deliberate: the properties
// they protect are properties of the code as written, not of a value at runtime,
// and neither is expressible any other way without a lot more machinery than
// either is worth.
// ---------------------------------------------------------------------------

#[cfg(test)]
mod tests {
    use std::path::{Path, PathBuf};

    fn rs_files(dir: &Path, out: &mut Vec<PathBuf>) {
        let Ok(rd) = std::fs::read_dir(dir) else { return };
        for e in rd.flatten() {
            let p = e.path();
            if p.is_dir() {
                rs_files(&p, out);
            } else if p.extension().is_some_and(|x| x == "rs") {
                out.push(p);
            }
        }
    }

    fn crate_src(name: &str) -> PathBuf {
        // CARGO_MANIFEST_DIR is <ws>/crates/sodactl-mcp.
        Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap().join(name).join("src")
    }

    /// Guardrail 10 from the plan, as a test rather than a convention.
    ///
    /// On stdio, stdout is the JSON-RPC framing. One `println!` on a path that
    /// happens to run inside a tool call corrupts the stream, and the corruption
    /// surfaces as an unrelated client error several calls later. This will not
    /// catch a dependency that prints -- nothing cheap will -- but it catches the
    /// realistic case, which is a debugging print that outlived its debugging
    /// session.
    ///
    /// `sodactl-core` is in scope because it is linked into this process; a print
    /// there corrupts the protocol exactly as surely as one here. `sodactl-cli`
    /// is deliberately NOT in scope: it owns every `println!` in the workspace,
    /// and this crate does not depend on it.
    #[test]
    fn no_stdout_writes() {
        // Built from fragments so this test's own source does not match itself.
        // The alternative is an exemption marker, and an exemption marker on a
        // guardrail is the thing that eventually gets used on a real offender.
        let p = "print";
        let banned: Vec<String> = vec![
            format!("{p}!"),
            format!("{p}ln!"),
            "dbg".to_string() + "!",
            "std::io::std".to_string() + "out",
            "io::std".to_string() + "out()",
        ];

        // `eprintln!` ends in `println!`, and stderr logging is not merely
        // allowed here but required. So a hit only counts at a word boundary.
        let hit = |code: &str, pat: &str| {
            code.match_indices(pat).any(|(i, _)| {
                i == 0 || !matches!(code.as_bytes()[i - 1], b'a'..=b'z' | b'A'..=b'Z' | b'0'..=b'9' | b'_')
            })
        };

        let mut offenders = Vec::new();
        for krate in ["sodactl-mcp", "sodactl-core"] {
            let mut files = Vec::new();
            rs_files(&crate_src(krate), &mut files);
            for f in files {
                let text = std::fs::read_to_string(&f).unwrap();
                for (n, line) in text.lines().enumerate() {
                    // Prose mentions stdout constantly in this crate; only code
                    // can corrupt the stream.
                    let code = line.trim_start();
                    if code.starts_with("//") {
                        continue;
                    }
                    for pat in &banned {
                        if hit(code, pat) {
                            offenders.push(format!("{}:{}: {}", f.display(), n + 1, code));
                        }
                    }
                }
            }
        }
        assert!(
            offenders.is_empty(),
            "stdout is the MCP protocol stream -- these writes would corrupt it:\n{}",
            offenders.join("\n")
        );
    }

    /// `explain`'s catalogue is written beside the emitters, not inside them, so
    /// it can drift -- in both directions, and both are checked here.
    ///
    /// Forward: every documented code must appear somewhere in the emitting
    /// source (twice: the entry itself plus an emitter). Reverse: every code
    /// literal handed to `Finding::new` in `sodactl-core` must have a catalogue
    /// entry. The reverse scan leans on a style invariant -- the code literal
    /// sits on the call's own line or the one directly after it -- and ASSERTS
    /// that invariant at every call site, so a formatting drift fails the build
    /// loudly instead of silently skipping the site.
    ///
    /// This crate's `rr.rs` emits its one code through `RrFinding`, not
    /// `Finding::new`, so only the forward direction covers it -- enough to
    /// keep its entry from going stale.
    #[test]
    fn catalogue_covers_emitted_codes() {
        let mut files = Vec::new();
        rs_files(&crate_src("sodactl-core"), &mut files);
        rs_files(&crate_src("sodactl-mcp"), &mut files);
        let corpus: String =
            files.iter().filter_map(|f| std::fs::read_to_string(f).ok()).collect();

        let orphans: Vec<&str> = crate::explain::CATALOGUE
            .iter()
            .map(|d| d.code)
            // Two occurrences: the catalogue entry itself, and an emitter.
            .filter(|c| corpus.matches(*c).count() < 2)
            .collect();

        assert!(
            orphans.is_empty(),
            "documented in explain::CATALOGUE but emitted by nothing: {orphans:?}"
        );

        // Reverse direction. The pattern is built from fragments so neither
        // this test's own source nor the prose in `explain.rs` that quotes the
        // invariant can match; comment lines are skipped for the same reason.
        //
        // Only `sodactl-core` is scanned: it is the only crate constructing
        // `Finding`s through this call.
        let call = "Finding::".to_string() + "new(";
        // The first argument as written at every site: a SHOUTING_SNAKE string
        // literal, opening right after the paren or at the start of the next
        // line (rustfmt's two renderings of the call).
        fn code_at(s: &str) -> Option<&str> {
            let body = s.trim_start().strip_prefix('"')?;
            let lit = &body[..body.find('"')?];
            (!lit.is_empty() && lit.chars().all(|c| c.is_ascii_uppercase() || c == '_'))
                .then_some(lit)
        }

        let mut core_files = Vec::new();
        rs_files(&crate_src("sodactl-core"), &mut core_files);
        let mut sites = 0usize;
        let mut undocumented = Vec::new();
        for f in &core_files {
            let text = std::fs::read_to_string(f).unwrap();
            let lines: Vec<&str> = text.lines().collect();
            for (n, line) in lines.iter().enumerate() {
                let code_line = line.trim_start();
                if code_line.starts_with("//") {
                    continue;
                }
                let Some(at) = code_line.find(&call) else { continue };
                sites += 1;
                let lit = code_at(&code_line[at + call.len()..])
                    .or_else(|| code_at(lines.get(n + 1).copied().unwrap_or("")));
                // The asserted style invariant: a site the scan cannot read is
                // a build failure, never a skip -- a skip is how this direction
                // would quietly stop covering new emitters.
                let Some(lit) = lit else {
                    panic!(
                        "{}:{}: no SHOUTING_SNAKE code literal on the call line or the \
                         next -- the reverse catalogue scan relies on that style; keep \
                         the literal there or teach the scan the new shape",
                        f.display(),
                        n + 1
                    );
                };
                if crate::explain::lookup(lit).is_none() {
                    undocumented.push(format!("{lit} ({}:{})", f.display(), n + 1));
                }
            }
        }
        // A scan that finds (almost) nothing means the extraction broke, not
        // that the emitters vanished. 30 is far below the real count and far
        // above zero -- it only has to catch "the walk or the pattern died".
        assert!(sites > 30, "the reverse scan found only {sites} call sites -- it is broken");
        assert!(
            undocumented.is_empty(),
            "passed to Finding::new but missing from explain::CATALOGUE:\n{}",
            undocumented.join("\n")
        );
    }
}
